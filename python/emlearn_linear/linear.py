"""Linear models (MY contribution — upstream issue emlearn/emlearn#56).

Converts scikit-learn linear estimators to dependency-free C, following the
same Wrapper/save()/CompiledClassifier contract as upstream `trees.py`.

Supported: LogisticRegression (binary + multiclass), LinearRegression.
Method: 'inline' only in v1 (self-contained functions, no runtime header).
"""

import os

import numpy

from emlearn import common, cgen

SUPPORTED_ESTIMATORS = [
    'LogisticRegression',
    'LinearRegression',
]

MAX_FEATURES = 256


class Wrapper:
    def __init__(self, estimator, method='inline'):
        kind = type(estimator).__name__
        if kind not in SUPPORTED_ESTIMATORS:
            raise ValueError(
                f"Unsupported estimator '{kind}'. Supported: {SUPPORTED_ESTIMATORS}")
        if method != 'inline':
            raise ValueError(f"Unsupported method '{method}'. Only 'inline' in v1")
        if not hasattr(estimator, 'coef_'):
            raise ValueError(f"Estimator '{kind}' is not fitted (missing coef_)")

        self.kind = kind
        self.method = method
        self.is_classifier = kind == 'LogisticRegression'

        coef = numpy.asarray(estimator.coef_, dtype=numpy.float64)
        intercept = numpy.asarray(estimator.intercept_, dtype=numpy.float64).ravel()
        if coef.ndim == 1:
            coef = coef.reshape(1, -1)
        n_rows, n_features = coef.shape
        if n_features > MAX_FEATURES:
            raise ValueError(f"Too many features: {n_features} (max {MAX_FEATURES})")

        if self.is_classifier:
            classes = numpy.asarray(estimator.classes_)
            if len(classes) == 2 and n_rows == 1:
                # binary: single logit row, decides classes_[1] vs classes_[0]
                self.n_classes = 2
            elif n_rows == len(classes):
                # multinomial / one-vs-rest: one row per class
                self.n_classes = len(classes)
            else:
                raise ValueError(
                    f"Cannot map coef shape {coef.shape} to {len(classes)} classes")
            self.classes_ = classes
        else:
            if n_rows != 1:
                raise ValueError(f"LinearRegression must have 1 target, got {n_rows} rows")
            self.n_classes = 0
            self.classes_ = None

        self.coef_ = coef
        self.intercept_ = intercept
        self.n_features = n_features
        self._classifier = None  # lazy-built host parity harness

    # ------------------------------------------------------------------ C gen
    def _dot(self, row, features_var='features'):
        terms = ' + '.join(
            f'({features_var}[{j}]*{cgen.constant(v)})'
            for j, v in enumerate(row)
        )
        return f'({terms})' if terms else '(0.0f)'

    def save(self, name=None, file=None, include_proba=True):
        if name is None:
            if file is None:
                raise ValueError('Either name or file must be provided')
            name = os.path.splitext(os.path.basename(file))[0]
        cgen.assert_valid_identifier(name)

        n = self.n_features
        head = ("// !!! Generated by emlearn-linear (esp32-tinyml-deploy) !!!\n"
                "#include <stdint.h>\n#include <math.h>\n")

        if not self.is_classifier:
            b = cgen.constant(float(self.intercept_[0]))
            code = (head +
                f"static inline float {name}_predict(const float *features, int32_t features_length) {{\n"
                f"    if (features_length != {n}) return 0.0f;\n"
                f"    return {self._dot(self.coef_[0])} + {b};\n"
                f"}}\n")
        elif self.n_classes == 2:
            b = cgen.constant(float(self.intercept_[0]))
            c0 = int(self.classes_[0])
            c1 = int(self.classes_[1])
            code = (head +
                f"static const int32_t {name}_classes[2] = {{{c0}, {c1}}};\n"
                f"static inline float {name}_logit(const float *features, int32_t features_length) {{\n"
                f"    (void)features_length;\n"
                f"    return {self._dot(self.coef_[0])} + {b};\n"
                f"}}\n"
                f"static inline float {name}_sigmoid(float z) {{\n"
                f"    return 1.0f / (1.0f + expf(-z));\n"
                f"}}\n"
                f"static inline int32_t {name}_predict(const float *features, int32_t features_length) {{\n"
                f"    if (features_length != {n}) return -1;\n"
                f"    return {name}_classes[{name}_sigmoid({name}_logit(features, features_length)) >= 0.5f ? 1 : 0];\n"
                f"}}\n")
            if include_proba:
                code += (
                f"static inline int {name}_predict_proba(const float *features, int32_t features_length, float *out, int out_length) {{\n"
                f"    if (features_length != {n} || out_length < 2) return -1;\n"
                f"    const float p = {name}_sigmoid({name}_logit(features, features_length));\n"
                f"    out[0] = 1.0f - p; out[1] = p;\n"
                f"    return 0;\n"
                f"}}\n")
        else:
            k = self.n_classes
            rows = ', '.join(cgen.constant(float(v)) for v in self.coef_.ravel())
            biases = ', '.join(cgen.constant(float(v)) for v in self.intercept_)
            classes = ', '.join(str(int(c)) for c in self.classes_)
            code = (head +
                f"static const float {name}_coef[{k * n}] = {{{rows}}};\n"
                f"static const float {name}_bias[{k}] = {{{biases}}};\n"
                f"static const int32_t {name}_classes[{k}] = {{{classes}}};\n"
                f"static inline int32_t {name}_predict(const float *features, int32_t features_length) {{\n"
                f"    if (features_length != {n}) return -1;\n"
                f"    float best = -1e30f; int32_t arg = 0;\n"
                f"    for (int32_t c = 0; c < {k}; c++) {{\n"
                f"        float s = {name}_bias[c];\n"
                f"        for (int32_t j = 0; j < {n}; j++) s += features[j] * {name}_coef[c*{n}+j];\n"
                f"        if (s > best) {{ best = s; arg = c; }}\n"
                f"    }}\n"
                f"    return {name}_classes[arg];\n"
                f"}}\n")
            if include_proba:
                code += (
                f"static inline int {name}_predict_proba(const float *features, int32_t features_length, float *out, int out_length) {{\n"
                f"    if (features_length != {n} || out_length < {k}) return -1;\n"
                f"    float s[{k}]; float m = -1e30f;\n"
                f"    for (int32_t c = 0; c < {k}; c++) {{\n"
                f"        s[c] = {name}_bias[c];\n"
                f"        for (int32_t j = 0; j < {n}; j++) s[c] += features[j] * {name}_coef[c*{n}+j];\n"
                f"        if (s[c] > m) m = s[c];\n"
                f"    }}\n"
                f"    float sum = 0.0f;\n"
                f"    for (int32_t c = 0; c < {k}; c++) {{ s[c] = expf(s[c]-m); sum += s[c]; }}\n"
                f"    for (int32_t c = 0; c < {k}; c++) out[c] = s[c] / sum;\n"
                f"    return 0;\n"
                f"}}\n")

        if file:
            with open(file, 'w') as f:
                f.write(code)
        return code

    # ------------------------------------------------------- host parity (gcc)
    def _build_classifier(self):
        if self._classifier is not None:
            return
        name = 'emllin'
        code = self.save(name=name, include_proba=True)
        if self.is_classifier:
            call = f'{name}_predict(values, length)'
            proba = (f'{name}_predict_proba(values, length, outputs, N_CLASSES)'
                     if self.n_classes else None)
            self._classifier = common.CompiledClassifier(
                code, name=name, call=call, proba_call=proba,
                out_dtype='int', n_classes=self.n_classes or None)
        else:
            call = f'{name}_predict(values, length)'
            self._classifier = common.CompiledClassifier(
                code, name=name, call=call, out_dtype='float')

    def predict(self, X):
        self._build_classifier()
        return self._classifier.predict(X)

    def predict_proba(self, X):
        self._build_classifier()
        if not self.is_classifier:
            raise ValueError('predict_proba is only for classifiers')
        return self._classifier.predict_proba(X)

    def regress(self, X):
        self._build_classifier()
        if self.is_classifier:
            raise ValueError('regress is only for regressors')
        return self._classifier.regress(X)
